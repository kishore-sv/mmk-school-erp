export function getFeature(slug: string) {
  return features.find((feature) => feature.slug === slug)
}

export function featuresForModule(moduleSlug: string) {
  return features.filter((feature) => feature.moduleSlug === moduleSlug)
}

export function relatedFeatures(slug: string) {
  const current = getFeature(slug)
  if (!current) return []
  return features.filter((feature) => feature.moduleSlug === current.moduleSlug && feature.slug !== slug).slice(0, 4)
}
